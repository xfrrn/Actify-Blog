import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { mkdtemp, mkdir, writeFile, readFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { scryptSync } from "node:crypto";
import sharp from "sharp";
import { testDatabase } from "./postgres-test.mjs";
import { importSqlite } from "./admin.mjs";
import { database } from "../src/lib/cms-db.ts";
import { getContent, updateContent } from "../src/lib/cms-store.ts";
import { emptyTranslation, emptyProject } from "../src/lib/cms-types.ts";
import { login, validSession } from "../src/lib/admin-auth.ts";

const testDb = await testDatabase();
const root = await mkdtemp(join(tmpdir(), "actify-migration-test-"));
process.env.DATA_DIR = root;
const source = join(root, "legacy.sqlite");
try {
  await mkdir(join(root, "uploads"));
  const image = await sharp({ create: { width: 2, height: 3, channels: 3, background: "white" } }).png().toBuffer();
  const filename = "33333333-3333-4333-8333-333333333333.png";
  await writeFile(join(root, "uploads", filename), image);
  const zh = { ...emptyTranslation(), title: "原发布标题", description: "摘要", content: "## 正文" };
  const draft = { zh: { ...zh, title: "未发布编辑" }, en: { ...zh, title: "English draft" } };
  const project = { ...emptyProject(), name: "Existing project", order: 8, featured: true };
  const now = new Date().toISOString();
  const password = "migration-check-password";
  const credential = `test-salt:${scryptSync(password, "test-salt", 64).toString("hex")}`;
  const legacy = new DatabaseSync(source);
  legacy.exec(`
    CREATE TABLE content(id TEXT PRIMARY KEY, kind TEXT, slug TEXT, locked INTEGER, version INTEGER, data TEXT, published TEXT, deleted_at TEXT, updated_at TEXT);
    CREATE TABLE feedback(id INTEGER PRIMARY KEY, pain_point TEXT, search_query TEXT, locale TEXT, status TEXT, created_at TEXT);
    CREATE TABLE media(id TEXT PRIMARY KEY, filename TEXT, name TEXT, mime TEXT, size INTEGER, width INTEGER, height INTEGER, created_at TEXT);
    CREATE TABLE imports(source TEXT PRIMARY KEY, imported_at TEXT);
    CREATE TABLE settings(key TEXT PRIMARY KEY, value TEXT);
    CREATE TABLE sessions(hash TEXT PRIMARY KEY, expires INTEGER, credential TEXT);
    INSERT INTO sessions VALUES ('old-session',9999999999999,'old-credential');
  `);
  legacy.prepare("INSERT INTO content VALUES ('post','posts','existing-post',1,7,?,?,NULL,?)").run(JSON.stringify(draft), JSON.stringify({ zh }), now);
  legacy.prepare("INSERT INTO content VALUES ('project','projects','existing-project',1,4,?,?,NULL,?)").run(JSON.stringify(project), JSON.stringify(project), now);
  legacy.prepare("INSERT INTO feedback VALUES (41,'迁移反馈','私有词','zh','published',?)").run(now);
  legacy.prepare("INSERT INTO media VALUES ('image',?,'image.png','image/png',?,2,3,?)").run(filename, image.length, now);
  legacy.prepare("INSERT INTO imports VALUES ('posts:existing-post.zh.mdx',?)").run(now);
  legacy.prepare("INSERT INTO settings VALUES ('password',?)").run(credential);
  legacy.close();
  const sourceBytes = await readFile(source);
  assert.equal(await importSqlite(source), 4);
  const entry = await getContent("posts", "post");
  assert.equal(entry.version, 7); assert.equal(entry.locked, true);
  assert.deepEqual(entry.data, draft); assert.deepEqual(entry.published, { zh });
  assert.deepEqual((await getContent("projects", "project")).published, project);
  const db = await database();
  assert.equal((await db.query("SELECT count(*)::int AS n FROM sessions")).rows[0].n, 0, "Legacy sessions are revoked");
  const media = (await db.query("SELECT * FROM media")).rows[0];
  assert.equal(media.storage, "local"); assert.equal(media.url, `/media/${filename}`);
  assert.deepEqual(await readFile(join(root, "uploads", filename)), image);
  assert.equal((await db.query("INSERT INTO feedback(pain_point,locale) VALUES ('new','zh') RETURNING id")).rows[0].id, 42);
  assert.ok(await validSession(await login(password, "migration-test")), "Password hashes remain usable");
  await updateContent("posts", entry.id, { version: entry.version, action: "save", slug: entry.slug, data: { zh: { ...zh, title: "后台新修改" } } });
  assert.equal(await importSqlite(source), 0);
  assert.equal((await getContent("posts", "post")).data.zh.title, "后台新修改");
  assert.deepEqual(await readFile(source), sourceBytes, "SQLite source remains byte-for-byte unchanged");
  await testDb.next();
  const broken = new DatabaseSync(source);
  broken.prepare("INSERT INTO content SELECT 'duplicate',kind,slug,locked,version,data,published,deleted_at,updated_at FROM content WHERE id='post'").run();
  broken.close();
  await assert.rejects(importSqlite(source), (error) => error.code === "23505");
  assert.equal((await (await database()).query("SELECT count(*)::int AS n FROM content")).rows[0].n, 0, "Failed migration rolls back all rows");
  console.log("SQLite migration checks passed: drafts, translations, published snapshots, projects, media, feedback IDs, password hashes, repeat safety, rollback and unchanged source.");
} finally { await testDb.cleanup(); }
